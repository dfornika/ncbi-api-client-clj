(ns gen-routes
  "Generates src/cljc/ncbi_api_client/datasets/routes.cljc from the Datasets
  OpenAPI spec. Run with:

    clojure -X:gen-routes

  The route test (ncbi-api-client.routes-test) regenerates the table and
  checks it against the checked-in file, so the two can't drift apart."
  (:require [clj-yaml.core :as yaml]
            [clojure.string :as str]))

(def spec-path "spec/datasets-openapi3.yaml")
(def out-path "src/cljc/ncbi_api_client/datasets/routes.cljc")

(defn op-keyword
  "An operationId as a keyword, the way Martian named them:
  BioSample_dataset_report -> :bio-sample-dataset-report."
  [operation-id]
  (-> operation-id
      (str/replace #"([a-z0-9])([A-Z])" "$1-$2")
      (str/replace #"([a-zA-Z])([0-9])" "$1-$2")
      (str/replace "_" "-")
      str/lower-case
      keyword))

(defn- media-types [op]
  (set (keys (get-in op ["responses" "200" "content"]))))

(defn- response-format
  "How to read a successful response, and what to ask for."
  [op]
  (let [types (media-types op)
        image (first (sort (filter #(and (str/starts-with? % "image/")
                                         (not= % "image/svg+xml"))
                                   types)))]
    (cond
      (types "application/json") {:as :json :accept "application/json"}
      (types "application/zip")  {:as :bytes :accept "application/zip"}
      image                      {:as :bytes :accept image}
      :else                      {:as :text :accept (or (first (sort types)) "text/plain")})))

(defn routes
  "The route table, from the spec at `path`."
  ([] (routes spec-path))
  ([path]
   (let [spec (yaml/parse-string (slurp path) :keywords false)]
     (into (sorted-map)
           (for [[path methods] (get spec "paths")
                 [method op] methods
                 :when (and (map? op) (get op "operationId"))
                 :let [params (get op "parameters")
                       query (into (sorted-set)
                                   (comp (filter #(= "query" (get % "in")))
                                         (map #(get % "name")))
                                   params)]]
             [(op-keyword (get op "operationId"))
              (cond-> (merge {:method (keyword method) :path path}
                             (response-format op))
                (seq query) (assoc :query query)
                (get op "requestBody") (assoc :body true))])))))

(defn- render [table]
  (str ";; Generated by scripts/gen_routes.clj from " spec-path ". Don't edit by hand:\n"
       ";; run `clojure -X:gen-routes` instead.\n"
       "(ns ncbi-api-client.datasets.routes\n"
       "  \"The Datasets API's operations, as data: method, path template, query\n"
       "  parameter names, and how to read the response (:as :json, :text or :bytes).\n"
       "  A route with :body true takes a JSON body.\")\n\n"
       "(def routes\n"
       "  {"
       (str/join "\n   "
                 (for [[k v] table]
                   (str (pr-str k) "\n   " (pr-str v))))
       "})\n"))

(defn rendered
  "The routes file's text, as it should be."
  []
  (render (routes)))

(defn write!
  "Write the routes file."
  [_]
  (spit out-path (rendered))
  (println "Wrote" out-path))
